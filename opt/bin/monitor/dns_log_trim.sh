#!/bin/sh
#------------------------------------------------------------------------------
#	ПАКЕТ KVASEC — ограничение журнала DNS (cron, раз в минуту)
#------------------------------------------------------------------------------
#
# dnsmasq пишет журнал запросов постоянно (kvas-dns-log.dnsmasq) в /tmp (RAM).
# Держим последние MAX строк. Перезапись на месте (cat >), а не mv: dnsmasq держит
# файл открытым и после mv писал бы в удалённый inode. Строки, дописанные между
# tail и cat, теряются — для истории «последних 100» это не важно.
#------------------------------------------------------------------------------

LOG=${KVAS_DNS_LOG:-/tmp/kvas-dns.log}
MAX=${KVAS_DNS_LOG_MAX_LINES:-20000}

[ -f "${LOG}" ] || exit 0
lines=$(wc -l < "${LOG}" 2>/dev/null || echo 0)
# Запас 25%: не переписывать файл каждую минуту.
[ "${lines}" -gt $((MAX + MAX / 4)) ] || exit 0
tmp=$(mktemp /tmp/kvas-dns-trim.XXXXXX) || exit 0
tail -n "${MAX}" "${LOG}" > "${tmp}" && cat "${tmp}" > "${LOG}"
rm -f "${tmp}"
